#!/usr/bin/env node
// Generates services/frontend/src/config/tenants.gen.ts from the canonical
// tenant manifests (tenants/modules.json + tenants/<id>.json).
//
// Why a generated, COMMITTED file: the frontend Docker build context is
// services/frontend, so it can't read the repo-root tenants/ manifests at build
// time. We commit the generated slice and verify freshness in CI (`node
// scripts/gen-tenant-config.mjs && git diff --exit-code`), the same discipline
// as a lockfile. Terraform and start_services.sh read the JSON manifests
// natively, so this is the only layer that needs generation.
//
// Run after editing any tenants/*.json:  node scripts/gen-tenant-config.mjs

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TENANTS_DIR = join(ROOT, "tenants");
const OUT = join(ROOT, "services/frontend/src/config/tenants.gen.ts");

// Strip documentation-only keys (anything starting with "_") recursively.
function strip(value) {
  if (Array.isArray(value)) return value.map(strip);
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value)
        .filter(([k]) => !k.startsWith("_"))
        .map(([k, v]) => [k, strip(v)]),
    );
  }
  return value;
}

const readJson = (p) => JSON.parse(readFileSync(p, "utf8"));

const catalog = strip(readJson(join(TENANTS_DIR, "modules.json")));
const moduleKeys = Object.keys(catalog.modules);

const tenantFiles = readdirSync(TENANTS_DIR)
  .filter((f) => f.endsWith(".json") && f !== "modules.json")
  .sort();

const tenants = {};
for (const file of tenantFiles) {
  const t = strip(readJson(join(TENANTS_DIR, file)));
  // Validate enabledModules against the catalog so a typo fails the build, not prod.
  const mods = t.enabledModules;
  if (mods !== "*") {
    if (!Array.isArray(mods)) {
      throw new Error(`${file}: enabledModules must be "*" or an array`);
    }
    for (const m of mods) {
      if (!moduleKeys.includes(m)) {
        throw new Error(`${file}: unknown module "${m}" (catalog has: ${moduleKeys.join(", ")})`);
      }
    }
  }
  tenants[t.id] = t;
}

const banner =
  "// AUTO-GENERATED by scripts/gen-tenant-config.mjs from tenants/*.json.\n" +
  "// Do NOT edit by hand — edit the manifests and re-run the generator.\n";

const body =
  `${banner}\n` +
  `export const MODULE_CATALOG = ${JSON.stringify(catalog, null, 2)} as const;\n\n` +
  `export const TENANTS = ${JSON.stringify(tenants, null, 2)} as const;\n`;

writeFileSync(OUT, body);
console.log(`✔ wrote ${OUT} (${tenantFiles.length} tenants: ${Object.keys(tenants).join(", ")})`);
